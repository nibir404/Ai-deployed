// Generates *.dark.svg variants of the small pixel icons (dark ink -> light ink,
// cobalt -> dark-theme cobalt) and the CSS that swaps them in under [data-theme="dark"].
// Large multi-colour illustrations are left alone. Re-run after adding icons.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DIR = path.join(ROOT, "public", "assets");
const OUT = path.join(ROOT, "src", "app", "dark-icons.css");
const MAX_FILLS = 12; // icons are a handful of paths; illustrations have hundreds

const rules = [];
for (const f of fs.readdirSync(DIR)) {
  if (!f.endsWith(".svg") || f.endsWith(".dark.svg")) continue;
  const src = fs.readFileSync(path.join(DIR, f), "utf8");
  const fills = src.match(/(fill|stroke)="#[0-9A-Fa-f]{6}"/g) || [];
  if (fills.length > MAX_FILLS || !/#1B1B1B|#3B43D6/i.test(src)) continue;
  const dark = src.replace(/#1B1B1B/gi, "#F2F2EE").replace(/#3B43D6/gi, "#6A71F2");
  const name = f.replace(/\.svg$/, ".dark.svg");
  fs.writeFileSync(path.join(DIR, name), dark);
  rules.push(
    `:root[data-theme="dark"] img[src$="/assets/${f}"] { content: url("/assets/${name}"); }`,
    `:root[data-theme="dark"] [style*="/assets/${f}"] { background-image: url("/assets/${name}") !important; }`,
  );
}
fs.writeFileSync(OUT, `/* Generated by scripts/dark-icons.mjs — do not edit. */\n${rules.join("\n")}\n`);
console.log(`${rules.length / 2} icons -> ${path.relative(ROOT, OUT)}`);
